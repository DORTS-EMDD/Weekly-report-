def markdown_fragment_to_html(md: str, marker_cleaner, url_compactor) -> str:
    """Convert a report fragment to the existing Streamlit card markup."""
    md = url_compactor(marker_cleaner(md))

    def _inline(line: str) -> str:
        html = escape(line)
        html = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", html)
        return re.sub(r"\[(.+?)\]\((https?://[^\s\)]+)\)", r'<a href="\2" target="_blank">\1</a>', html)

    rows = []
    for raw_line in md.splitlines():
        line = raw_line.strip()
        if not line or line == "---":
            rows.append('<div class="report-spacer"></div>')
        elif line.startswith(("- ", "* ")):
            rows.append(f'<div class="report-line list">• {_inline(line[2:].strip())}</div>')
        elif line.startswith("> "):
            rows.append(f'<div class="report-line meta">{_inline(line[2:].strip())}</div>')
        else:
            rows.append(f'<div class="report-line">{_inline(line)}</div>')
    return "".join(rows)
